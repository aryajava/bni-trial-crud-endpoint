-- 3) Tabel pengaturan aplikasi (nilai global; lockout = SA, ongkir/pajak = OWNER/SA)
IF NOT EXISTS (SELECT 1 FROM sys.tables WHERE schema_id = SCHEMA_ID('LOSCONSUMER') AND name = 'APP_SETTING')
BEGIN
    CREATE TABLE LOSCONSUMER.APP_SETTING (
        ID            INT             NOT NULL IDENTITY(1,1) PRIMARY KEY,
        SETTING_KEY   NVARCHAR(100)   NOT NULL UNIQUE,
        SETTING_VALUE NVARCHAR(500)   NOT NULL,
        IS_ACTIVE     BIT             NOT NULL DEFAULT 1,
        CREATED_AT    DATETIME2       NOT NULL DEFAULT GETDATE(),
        CREATED_BY    NVARCHAR(100)   NOT NULL DEFAULT 'SYSTEM',
        UPDATED_AT    DATETIME2       NULL,
        UPDATED_BY    NVARCHAR(100)   NULL,
        VERSION       INT             NOT NULL DEFAULT 1
    );
END;

