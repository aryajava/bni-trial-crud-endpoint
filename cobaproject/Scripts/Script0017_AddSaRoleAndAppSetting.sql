BEGIN
    ALTER TABLE LOSCONSUMER.MASTER_USER DROP CONSTRAINT CK_MASTER_USER_ROLE;
    ALTER TABLE LOSCONSUMER.MASTER_USER ADD CONSTRAINT CK_MASTER_USER_ROLE CHECK (ROLE IN ('SA', 'OWNER', 'ADMIN'));
END;

